// Imports vocabulary from the VpngoPlay project (../vpngoplay/public/decks) into
// src/game/content/vocab-{en,ja,zh}.ts as bank text the LIVE games read.
//
//   node scripts/import-vpngoplay.mjs [path/to/vpngoplay]
//
// Lines: English "word | nghĩa"; Japanese "語 | kana/romaji | nghĩa";
// Chinese "汉字 | pinyin | nghĩa". Re-run after the decks change.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(process.argv[2] ?? '../vpngoplay');
const decksDir = join(root, 'public/decks');
const outDir = resolve('src/game/content');

const LANGS = ['en', 'ja', 'zh'];
/** Topic sets (decks of one track merged) and the core course split in parts. */
const TOPICS = [
  { key: 'kids', label: { en: 'Trẻ em (con vật, gia đình, đồ ăn…)', ja: 'Trẻ em (con vật, gia đình, đồ ăn…)', zh: 'Trẻ em (con vật, gia đình, đồ ăn…)' }, match: /-kids-/ },
  { key: 'exam', label: { en: 'Luyện thi IELTS', ja: 'Luyện thi JLPT N5–N3', zh: 'Luyện thi HSK 1–4' }, match: /-exam-/ },
  { key: 'work', label: { en: 'Công sở', ja: 'Công sở', zh: 'Công sở' }, match: /-work-/ },
  { key: 'idioms', label: { en: 'Thành ngữ', ja: 'Thành ngữ, tục ngữ', zh: 'Thành ngữ 成语' }, match: /-idioms-/ }
];
const COURSE_PART = 500;
const COURSE_PARTS = 4;

const MAX_MEANING = 48;

/** "chiên, rán, cá con" → the first senses that fit in MAX_MEANING characters. */
function shortMeaning(meaning) {
  const clean = meaning.replace(/\s+/g, ' ').replace(/\|/g, '/').trim();
  if (clean.length <= MAX_MEANING) return clean;
  const parts = clean.split(/[,;]\s*/);
  let out = parts[0] ?? '';
  for (const part of parts.slice(1)) {
    if (`${out}, ${part}`.length > MAX_MEANING) break;
    out = `${out}, ${part}`;
  }
  return out.slice(0, MAX_MEANING).trim();
}

/** One bank line, or null for words a viewer can't type back. */
function line(lang, word, emoji) {
  const term = String(word.term ?? '').trim();
  const reading = String(word.reading ?? '').trim();
  let meaning = shortMeaning(String(word.meaning ?? ''));
  if (!term || !meaning || term.includes('|')) return null;
  if (emoji) meaning = `${emoji} ${meaning}`;
  if (lang === 'en') {
    if (!/^[A-Za-z][A-Za-z' -]{0,30}$/.test(term)) return null;
    return `${term} | ${meaning}`;
  }
  // "らいねん · rainen" → "らいねん/rainen"; pinyin stays as it is.
  const readings = reading.split(/\s*[·/]\s*/).filter(Boolean).join('/');
  if (!readings || readings.includes('|')) return null;
  return `${term} | ${readings} | ${meaning}`;
}

function readDeck(file) {
  return JSON.parse(readFileSync(join(decksDir, file), 'utf8'));
}

function uniqueLines(lines) {
  const seen = new Set();
  return lines.filter((text) => {
    if (!text) return false;
    const key = text.split('|')[0].trim().toLowerCase();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

const files = readdirSync(decksDir).filter((file) => file.endsWith('.json') && file !== 'index.json').sort();

for (const lang of LANGS) {
  const sets = [];
  for (const topic of TOPICS) {
    const decks = files.filter((file) => file.startsWith(`${lang}-`) && topic.match.test(file)).map(readDeck);
    const lines = uniqueLines(decks.flatMap((deck) => deck.words.map((word) => line(lang, word, topic.key === 'kids' ? word.emoji : ''))));
    if (lines.length) sets.push({ key: `${lang}-${topic.key}`, label: topic.label[lang], lines });
  }
  const course = files
    .filter((file) => new RegExp(`^${lang}-basic-\\d+\\.json$`).test(file))
    .map(readDeck)
    .sort((a, b) => a.lesson - b.lesson);
  const courseLines = uniqueLines(course.flatMap((deck) => deck.words.map((word) => line(lang, word, ''))));
  for (let part = 0; part < COURSE_PARTS; part += 1) {
    const lines = courseLines.slice(part * COURSE_PART, (part + 1) * COURSE_PART);
    if (lines.length < 50) break;
    const from = part * COURSE_PART + 1;
    sets.push({ key: `${lang}-basic${part + 1}`, label: `Cơ bản ${part + 1} (từ ${from}–${from + lines.length - 1})`, lines });
  }

  const extra = [];
  if (lang === 'en') {
    // Wordle: every 4–6 letter word of the basic and intermediate courses.
    const decks = files.filter((file) => /^en-(basic|intermediate)-\d+\.json$/.test(file)).map(readDeck);
    const words = uniqueLines(
      decks.flatMap((deck) => deck.words.filter((word) => /^[a-z]{4,6}$/.test(word.term)).map((word) => line('en', word, '')))
    );
    extra.push(`/** Đoán chữ (Wordle): 4–6 letter words of the basic and intermediate courses — word | nghĩa. */`);
    extra.push(`export const EN_WORDLE_BANK = ${JSON.stringify(words.join('\n'))};`);
  }

  const name = lang.toUpperCase();
  const body = [
    '// Generated by scripts/import-vpngoplay.mjs from the VpngoPlay decks — do not edit by hand.',
    `// ${lang === 'en' ? 'word | nghĩa' : lang === 'ja' ? '語 | kana/romaji | nghĩa' : '汉字 | pinyin | nghĩa'}`,
    '',
    `export const ${name}_VOCAB_SETS: Record<string, { label: string; bank: string }> = {`,
    ...sets.map((set, index) => `  ${JSON.stringify(set.key)}: { label: ${JSON.stringify(set.label)}, bank: ${JSON.stringify(set.lines.join('\n'))} }${index < sets.length - 1 ? ',' : ''}`),
    '};',
    '',
    ...extra,
    ''
  ].join('\n');
  writeFileSync(join(outDir, `vocab-${lang}.ts`), body);
  console.log(`vocab-${lang}.ts: ${sets.map((set) => `${set.key} ${set.lines.length}`).join(', ')}`);
}
